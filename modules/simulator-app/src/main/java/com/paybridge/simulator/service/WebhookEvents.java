package com.paybridge.simulator.service;

import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.time.temporal.ChronoUnit;
import java.util.HexFormat;
import java.util.Locale;
import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;

/**
 * Webhook bodies and signatures (API contract 8.4). The body is one line with a fixed field order and no extra
 * whitespace; it is stored once and every retry sends exactly the same bytes with a fresh timestamp and signature.
 */
public final class WebhookEvents {
    private static final DateTimeFormatter ISO_MILLIS = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss.SSS'Z'", Locale.ROOT)
            .withZone(ZoneOffset.UTC);

    private WebhookEvents() {}

    public static String iso(Instant instant) {
        return ISO_MILLIS.format(instant.truncatedTo(ChronoUnit.MILLIS));
    }

    /** All inputs are generated by the simulator (UUIDs, ids, digits), so none needs JSON escaping. */
    public static String body(String eventId, String providerKey, String reference, long revision, boolean succeeded,
                              Instant observedAt, String amountMinor, String currency) {
        return "{\"eventId\":\"" + eventId + "\",\"eventType\":\"" + (succeeded ? "charge.succeeded" : "charge.declined")
                + "\",\"providerKey\":\"" + providerKey + "\",\"reference\":\"" + reference + "\",\"revision\":" + revision
                + ",\"outcome\":\"" + (succeeded ? "SUCCEEDED" : "DECLINED") + "\",\"observedAt\":\"" + iso(observedAt)
                + "\",\"amountMinor\":\"" + amountMinor + "\",\"currency\":\"" + currency + "\"}";
    }

    /** {@code v1=} plus lower case hex HMAC-SHA256(secret, timestamp + "." + rawBody). */
    public static String signature(String secret, long timestamp, byte[] rawBody) {
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(secret.getBytes(StandardCharsets.UTF_8), "HmacSHA256"));
            mac.update((timestamp + ".").getBytes(StandardCharsets.US_ASCII));
            return "v1=" + HexFormat.of().formatHex(mac.doFinal(rawBody));
        } catch (java.security.GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }
}
