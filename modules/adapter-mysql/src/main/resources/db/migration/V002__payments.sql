-- PayBridge V002: payments, idempotency reservations and attempts (DMR section 2).
CREATE TABLE payment (
  id                 CHAR(36) CHARACTER SET ascii COLLATE ascii_bin       NOT NULL,
  merchant_id        CHAR(36) CHARACTER SET ascii COLLATE ascii_bin       NOT NULL,
  invoice_id         CHAR(36) CHARACTER SET ascii COLLATE ascii_bin       NOT NULL,
  method_code        VARCHAR(32)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  method_token       VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  amount_minor       BIGINT       NOT NULL,
  currency           CHAR(3)      NOT NULL,
  status             ENUM('REQUESTED','PROCESSING','SUCCEEDED','FAILED','UNKNOWN') NOT NULL,
  aggregate_version  BIGINT       NOT NULL,
  version            BIGINT       NOT NULL DEFAULT 0,
  provider_key       VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider_reference VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NULL,
  provider_revision  BIGINT       NULL,
  decline_code       VARCHAR(40)  CHARACTER SET ascii NULL,
  scenario_run_id    VARCHAR(64)  CHARACTER SET ascii NOT NULL DEFAULT 'default',
  correlation_id     VARCHAR(64)  CHARACTER SET ascii NOT NULL,
  requested_by       CHAR(36) CHARACTER SET ascii COLLATE ascii_bin       NOT NULL,
  created_at         DATETIME(6)  NOT NULL,
  updated_at         DATETIME(6)  NOT NULL,
  completed_at       DATETIME(6)  NULL,
  -- Hard guarantee for FR-009: at most one non-FAILED payment per invoice.
  blocking_invoice_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS (CASE WHEN status <> 'FAILED' THEN invoice_id END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY ux_payment_one_active (blocking_invoice_id),
  UNIQUE KEY ux_payment_provider_key (provider_key),
  KEY ix_payment_list (merchant_id, created_at DESC, id DESC),
  KEY ix_payment_status_list (merchant_id, status, created_at DESC, id DESC),
  KEY ix_payment_status_created (status, created_at),
  KEY ix_payment_invoice (invoice_id, created_at),
  KEY ix_payment_provider_ref (provider_reference),
  CONSTRAINT ck_payment_amount  CHECK (amount_minor > 0),
  CONSTRAINT ck_payment_version CHECK (aggregate_version >= 1),
  CONSTRAINT fk_payment_merchant FOREIGN KEY (merchant_id) REFERENCES merchant (id),
  CONSTRAINT fk_payment_invoice  FOREIGN KEY (invoice_id)  REFERENCES invoice (id),
  CONSTRAINT fk_payment_user     FOREIGN KEY (requested_by) REFERENCES app_user (id)
) ENGINE=InnoDB;
 
ALTER TABLE invoice
  ADD CONSTRAINT fk_invoice_active_payment FOREIGN KEY (active_payment_id) REFERENCES payment (id);
 
-- The reservation row is inserted before the payment row (TIS section 9), so payment_id is NOT a
-- foreign key. Atomicity of the single admission transaction plus the recovery checks below
-- replace the constraint. payment_id is generated by the application before the insert.
CREATE TABLE payment_request (
  id              CHAR(36) CHARACTER SET ascii COLLATE ascii_bin      NOT NULL,
  merchant_id     CHAR(36) CHARACTER SET ascii COLLATE ascii_bin      NOT NULL,
  operation       VARCHAR(32) CHARACTER SET ascii NOT NULL,
  idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin      NOT NULL,
  request_hash    CHAR(64)    CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payment_id      CHAR(36) CHARACTER SET ascii COLLATE ascii_bin      NOT NULL,
  requested_by    CHAR(36) CHARACTER SET ascii COLLATE ascii_bin      NOT NULL,
  created_at      DATETIME(6) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ux_payment_request (merchant_id, operation, idempotency_key),
  KEY ix_payment_request_payment (payment_id)
) ENGINE=InnoDB;
 
CREATE TABLE payment_attempt (
  id                 CHAR(36) CHARACTER SET ascii COLLATE ascii_bin      NOT NULL,
  payment_id         CHAR(36) CHARACTER SET ascii COLLATE ascii_bin      NOT NULL,
  attempt_number     INT         NOT NULL,
  provider_key       VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind               ENUM('CHARGE','LOOKUP','REPEAT_CHARGE') NOT NULL,
  observation        ENUM('SUCCEEDED','DECLINED','PENDING','UNKNOWN') NULL,
  error_class        ENUM('NONE','RETRYABLE_UNAVAILABLE','TRANSPORT_UNCERTAIN','MALFORMED') NOT NULL DEFAULT 'NONE',
  provider_reference VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  provider_revision  BIGINT      NULL,
  http_status        SMALLINT    NULL,
  lease_owner        VARCHAR(80) CHARACTER SET ascii NULL,
  lease_token        BIGINT      NULL,
  started_at         DATETIME(6) NOT NULL,
  finished_at        DATETIME(6) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ux_payment_attempt_number (payment_id, attempt_number),
  CONSTRAINT fk_attempt_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
) ENGINE=InnoDB;

