-- PayBridge V003: durable work: events, outbox, tasks, webhook inbox, reconciliation cases (DMR section 2).
CREATE TABLE payment_event (
  seq               BIGINT       NOT NULL AUTO_INCREMENT,
  event_id          CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payment_id        CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  merchant_id       CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  event_class       ENUM('STATE','SUPPORT') NOT NULL,
  event_type        VARCHAR(48)  CHARACTER SET ascii NOT NULL,
  schema_version    INT          NOT NULL,
  aggregate_version BIGINT       NOT NULL,
  occurred_at       DATETIME(6)  NOT NULL,
  correlation_id    VARCHAR(64)  CHARACTER SET ascii NOT NULL,
  payload           JSON         NOT NULL,
  -- one STATE event per aggregate version; SUPPORT events share the current version
  state_version     BIGINT GENERATED ALWAYS AS (CASE WHEN event_class = 'STATE' THEN aggregate_version END) STORED,
  PRIMARY KEY (event_id),
  UNIQUE KEY ux_event_seq (seq),
  UNIQUE KEY ux_event_state_version (payment_id, state_version),
  KEY ix_event_payment (payment_id, aggregate_version, seq),
  KEY ix_event_merchant_seq (merchant_id, seq),
  CONSTRAINT fk_event_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
) ENGINE=InnoDB;

CREATE TABLE outbox (
  id          BIGINT       NOT NULL AUTO_INCREMENT,
  event_id    CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  destination ENUM('COMMAND','STATUS') NOT NULL,
  exchange    VARCHAR(64)  CHARACTER SET ascii NOT NULL,
  routing_key VARCHAR(64)  CHARACTER SET ascii NOT NULL,
  status      ENUM('PENDING','LEASED','PUBLISHED') NOT NULL DEFAULT 'PENDING',
  due_at      DATETIME(6)  NOT NULL,
  lease_owner VARCHAR(80)  CHARACTER SET ascii NULL,
  lease_token BIGINT       NOT NULL DEFAULT 0,
  lease_until DATETIME(6)  NULL,
  attempts    INT          NOT NULL DEFAULT 0,
  last_error  VARCHAR(255) NULL,
  created_at  DATETIME(6)  NOT NULL,
  published_at DATETIME(6) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ux_outbox_event_destination (event_id, destination),
  KEY ix_outbox_runnable (status, due_at, id),
  KEY ix_outbox_lease (status, lease_until),
  CONSTRAINT fk_outbox_event FOREIGN KEY (event_id) REFERENCES payment_event (event_id)
) ENGINE=InnoDB;

CREATE TABLE processing_task (
  id           CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  task_key     VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind         ENUM('COLLECT','VERIFY_PENDING','RECONCILE','WEBHOOK_APPLY','REPLAY') NOT NULL,
  payment_id   CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  command_event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  state        ENUM('PENDING','RUNNING','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  due_at       DATETIME(6)  NOT NULL,
  deadline_at  DATETIME(6)  NULL,
  lease_owner  VARCHAR(80)  CHARACTER SET ascii NULL,
  lease_token  BIGINT       NOT NULL DEFAULT 0,
  lease_until  DATETIME(6)  NULL,
  attempt_count INT         NOT NULL DEFAULT 0,
  check_count  INT          NOT NULL DEFAULT 0,
  params       JSON         NULL,
  last_error   VARCHAR(255) NULL,
  created_at   DATETIME(6)  NOT NULL,
  updated_at   DATETIME(6)  NOT NULL,
  completed_at DATETIME(6)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ux_task_key (task_key),
  UNIQUE KEY ux_task_command_event (command_event_id),
  KEY ix_task_runnable (state, due_at, id),
  KEY ix_task_lease (state, lease_until),
  KEY ix_task_payment (payment_id),
  CONSTRAINT fk_task_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
) ENGINE=InnoDB;

CREATE TABLE webhook_inbox (
  id                 CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider           VARCHAR(32)  CHARACTER SET ascii NOT NULL,
  event_id           VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider_key       VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NULL,
  provider_reference VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider_revision  BIGINT       NOT NULL,
  outcome            ENUM('SUCCEEDED','DECLINED','PENDING','UNKNOWN') NOT NULL,
  observed_at        DATETIME(6)  NOT NULL,
  transport_timestamp DATETIME(6) NOT NULL,
  payment_id         CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  state              ENUM('RECEIVED','APPLIED','IGNORED_STALE','QUARANTINED','FAILED') NOT NULL DEFAULT 'RECEIVED',
  payload            JSON         NOT NULL,
  received_at        DATETIME(6)  NOT NULL,
  processed_at       DATETIME(6)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ux_webhook_provider_event (provider, event_id),
  KEY ix_webhook_state (state, received_at),
  KEY ix_webhook_reference (provider_reference)
) ENGINE=InnoDB;

CREATE TABLE reconciliation_case (
  id                  CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payment_id          CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  merchant_id         CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  state               ENUM('OPEN','ACTION_REQUIRED','RESOLVED') NOT NULL,
  reason              ENUM('PROVIDER_TIMEOUT','TRANSPORT_UNCERTAIN','PENDING_DEADLINE','RETRY_EXHAUSTED','CONFLICTING_TERMINAL','PROVIDER_IDEMPOTENCY_CONFLICT','PROVIDER_REJECTED') NOT NULL,
  provider_key        VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  check_count         INT         NOT NULL DEFAULT 0,
  manual_check_count  INT         NOT NULL DEFAULT 0,
  next_check_at       DATETIME(6) NULL,
  evidence            JSON        NULL,
  resolution          ENUM('PROVIDER_SUCCEEDED','PROVIDER_DECLINED','INVESTIGATION_CLOSED') NULL,
  opened_at           DATETIME(6) NOT NULL,
  updated_at          DATETIME(6) NOT NULL,
  resolved_at         DATETIME(6) NULL,
  resolved_by         CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  version             BIGINT      NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY ux_case_payment (payment_id),
  KEY ix_case_merchant_state (merchant_id, state, opened_at DESC, id DESC),
  KEY ix_case_state_next (state, next_check_at),
  CONSTRAINT fk_case_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
) ENGINE=InnoDB;
